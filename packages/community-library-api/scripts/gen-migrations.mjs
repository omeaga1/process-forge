// Writes src/migrations.generated.ts from migrations/*.sql, so the worker can
// apply its own schema changes (see src/schema.ts). Run after adding a
// migration: `pnpm migrations:gen`. A test fails if the two disagree.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'migrations');
const files = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();
const entries = files.map((f) => `  { name: ${JSON.stringify(f.replace(/\.sql$/, ''))}, sql: ${JSON.stringify(readFileSync(join(dir, f), 'utf8').replace(/\r\n/g, '\n'))} }`);
writeFileSync(
  join(root, 'src', 'migrations.generated.ts'),
  `// Generated by scripts/gen-migrations.mjs from migrations/*.sql. Do not edit.\nexport const MIGRATIONS: { name: string; sql: string }[] = [\n${entries.join(',\n')}\n];\n`
);
console.log(`migrations.generated.ts: ${files.length} migrations`);
